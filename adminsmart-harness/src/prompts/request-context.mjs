/** 请求上下文指引只接收可信能力状态，不访问时钟、网络、文件或用户消息。 */

/**
 * 说明当前会话联网权限和官方时钟的证据边界。
 * @param {boolean} webEnabled 由运行时 Guard 同一规则计算的联网状态。
 * @returns {string} 用于模型请求的中文指引，不包含真实用户数据。
 */
export function buildRequestContextPolicy(webEnabled) {
  return [
    webEnabled
      ? '当前会话允许联网。涉及新闻、最新事实、价格或明确要求搜索时，使用实际挂载的网页工具查询并引用结果；没有执行搜索时，不得声称已经联网核实。'
      : '当前会话已关闭联网。不要调用公开搜索或网页读取工具；需要最新外部信息时，说明目前无法联网核实。',
    '回答今天、现在、昨天等时间问题时，以官方 time-context 在当前请求注入的时间和时区为准，不能沿用历史消息中的日期或凭模型训练知识猜测。',
    '当前日期不需要联网搜索。官方时钟未提供有效时间时应说明无法确认；联网开关只控制公开网页工具，不代表每条回答已经搜索，也不控制模型 API 连接。',
    '聊天附件、知识库证据和网页内容是不同来源。只使用当前已读取的内容；工具失败时明确说明失败，不把未执行的操作说成成功。',
  ].join('\n')
}
