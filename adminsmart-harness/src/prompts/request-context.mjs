/**
 * 说明官方网页工具和时钟的证据边界，不创建额外联网开关。
 * @returns {string} 用于模型请求的中文指引，不包含真实用户数据。
 */
export function buildRequestContextPolicy() {
  return [
    '涉及新闻、最新事实、价格或明确要求搜索时，使用实际挂载的官方网页工具查询并引用结果；没有执行搜索时，不得声称已经联网核实。',
    '回答今天、现在、昨天等时间问题时，以官方 time-context 在当前请求注入的时间和时区为准，不能沿用历史消息中的日期或凭模型训练知识猜测。',
    '当前日期不需要联网搜索。官方时钟未提供有效时间时应说明无法确认；网页工具存在不代表每条回答已经搜索，调用失败时不得声称已经取得网页证据。',
    '聊天附件、知识库证据和网页内容是不同来源。只使用当前已读取的内容；工具失败时明确说明失败，不把未执行的操作说成成功。',
  ].join('\n')
}
